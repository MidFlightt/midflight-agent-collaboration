const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const script=fs.readFileSync('midflight/theater/source_graph.html','utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const context=vm.createContext({nodes:new Map(),lanes:new Map(),rowSlots:new Map()});
vm.runInContext(script.slice(script.indexOf('function slot('),script.indexOf('function fit(')),context);
const raw={plan_version:1,nodes:[{id:'agent:a',label:'a',kind:'agent'},{id:'agent:b',label:'b',kind:'agent'},{id:'ca',kind:'claim'},{id:'cb',kind:'claim'},{id:'interface:price',label:'price',kind:'interface'},{id:'declared',label:'not-created.py',kind:'file'}],edges:[{source:'agent:a',target:'ca',kind:'claims'},{source:'agent:b',target:'cb',kind:'claims'},{source:'ca',target:'interface:price',kind:'provides',fields:{total_cents:'integer'}},{source:'cb',target:'interface:price',kind:'consumes',fields:{total_cents:'integer'}},{source:'ca',target:'declared',kind:'declares'}],workspace_files:[{id:'disk:a:real.py',kind:'file',agent_id:'agent:a',label:'real.py',sha256:'real-hash',origin:'filesystem'}]};
raw.native_dependencies=[{provider:'a',consumer:'b',contract_id:'price',fields:{total_cents:'integer'}}];
context.raw=raw;
const view=vm.runInContext('simplify(raw)',context);
assert(!view.nodes.some(n=>n.label==='not-created.py'));
assert(view.nodes.some(n=>n.label==='real.py'&&n.origin==='filesystem'));
assert(view.edges.some(e=>e.source==='agent:a'&&e.target==='disk:a:real.py'&&e.kind==='workspace'));
const dependency=view.edges.find(e=>e.kind==='dependency');
assert.equal(dependency.label_lines[0],'price.total_cents');
assert(!dependency.label.includes('uses'));
for(const n of view.nodes)context.nodes.set(n.id,{...n});
context.view=view;vm.runInContext('hierarchy(view)',context);
assert(context.nodes.get('disk:a:real.py').y>context.nodes.get('agent:a').y);
raw.workspace_files=[];
assert(!vm.runInContext('simplify(raw)',context).nodes.some(n=>n.id==='disk:a:real.py'));
raw.native_dependencies=[];
assert(!vm.runInContext('simplify(raw)',context).edges.some(e=>e.kind==='dependency'));
console.log('Source graph checks passed: only observed files, no declared-only ghosts, exact contract labels, file ownership, removals.');
