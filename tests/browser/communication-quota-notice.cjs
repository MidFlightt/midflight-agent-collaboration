const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('midflight/communication/terminal.html', 'utf8');
const block = html.split('// BEGIN DEMO TEXT COLORS')[1].split('// END DEMO TEXT COLORS')[0];
const masks = vm.runInNewContext(block.slice(block.indexOf('\n') + 1) + ';quotaNoticeMasks');
const banner = '⚠ Heads up, you have less than 25% of your weekly limit left. Run /status for a breakdown.';
assert.equal(masks([banner], {billing:{x:0,y:0,width:120,height:1}}).length, 1);
const wrapped = banner.match(/.{1,29}/g);
assert.equal(masks(wrapped, {billing:{x:0,y:0,width:29,height:wrapped.length}}).length, wrapped.length);
assert.equal(masks(['Error: database unavailable', 'All tests passed'], {billing:{x:0,y:0,width:60,height:2}}).length, 0);
const left = 'Error: database unavailable'.padEnd(100);
const twoPanes = [left + banner];
const result = masks(twoPanes, {billing:{x:0,y:0,width:100,height:1},delivery:{x:100,y:0,width:100,height:1}});
assert.equal(result.length, 1);
assert.equal(result[0].x, 100, 'never mask neighboring agent output');
assert.equal(masks([banner], {}).length, 0, 'do not guess unknown pane boundaries');
new vm.Script(html.split('<script>')[1].split('</script>')[0]);
console.log('Quota notice: exact banner, wrapped lines and pane isolation passed');
